"""Generate mod/src/offsets_gen.hpp from mod/offsets/*.json.

The JSON files are the source of truth. Rerun this after editing them:
    python -I tools/gen_offsets.py
"""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "mod", "offsets")
OUT = os.path.join(ROOT, "mod", "src", "offsets_gen.hpp")


def ident(symbol):
    return re.sub(r"[^A-Za-z0-9]", "_", symbol.replace("::", "__"))


def main():
    builds = []
    symbols = set()
    for path in sorted(glob.glob(os.path.join(SRC, "*.json"))):
        d = json.load(open(path, encoding="utf-8"))
        fns = {f["symbol"]: int(f["rva"], 16) for f in d["functions"]}
        symbols |= set(fns)
        builds.append((d["build"], fns, os.path.basename(path)))
    symbols = sorted(symbols)
    lines = [
        "// GENERATED by tools/gen_offsets.py from mod/offsets/*.json. Do not edit by hand.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace gdbot::offsets {",
        "",
        "enum Fn : int {",
    ]
    lines += [f"    {ident(s)}," for s in symbols]
    lines += ["    FnCount", "};", ""]
    lines.append("inline const char* const kFnNames[FnCount] = {")
    lines += [f'    "{s}",' for s in symbols]
    lines += ["};", ""]
    lines += [
        "struct Build {",
        "    const char* game_version;",
        "    const char* exe_sha256;  // lowercase hex",
        "    const char* source_file;",
        "    uintptr_t rva[FnCount];  // 0 = not mapped for this build",
        "};",
        "",
        "inline const Build kBuilds[] = {",
    ]
    for build, fns, fname in builds:
        rvas = ", ".join(f"0x{fns.get(s, 0):x}" for s in symbols)
        lines.append(f'    {{"{build["game_version"]}", "{build["exe_sha256"].lower()}", "{fname}", {{{rvas}}}}},')
    lines += ["};", "", "}  // namespace gdbot::offsets", ""]
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print(f"wrote {OUT}: {len(builds)} build(s), {len(symbols)} symbols")


if __name__ == "__main__":
    main()
